#[test]
fn contact_sheet_preserves_failed_tiles_and_unicode_labels() {
    let (image, _) = images::encode_image(&pixel_image(10, 20), "png", 64, 85, false).unwrap();
    let (data, meta) = images::compose_contact_sheet(
        &[
            (image, "نام فارسی 👨‍👩‍👧".into()),
            (b"broken".to_vec(), "Second".into()),
        ],
        Some(2),
    )
    .unwrap();
    assert_eq!(meta["columns"], 2);
    assert_eq!(meta["rows"], 1);
    assert_eq!(meta["cells"][0]["label"], "نام فارسی 👨‍👩‍👧");
    assert_eq!(meta["cells"][0]["decoded"], true);
    assert_eq!(meta["cells"][1]["decoded"], false);
    assert_eq!(images::decode_image(&data).unwrap().width(), 512);
}
