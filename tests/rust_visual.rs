fn pixel_image(width: u32, height: u32) -> image::DynamicImage {
    image::DynamicImage::ImageRgba8(image::RgbaImage::from_pixel(
        width,
        height,
        image::Rgba([20, 90, 180, 255]),
    ))
}

#[test]
fn png_round_trip_preserves_pixels() {
    let source = pixel_image(21, 35);
    let (data, meta) = images::encode_image(&source, "png", 1568, 85, false).unwrap();
    let decoded = images::decode_image(&data).unwrap();
    assert_eq!(decoded.to_rgba8(), source.to_rgba8());
    assert_eq!(meta["mime_type"], "image/png");
    assert_eq!(meta["width"], 21);
    assert!(meta.get("downscaled").is_none());
}
