#[test]
fn json_message_resolves_sender_and_long_ids() {
    let peers = BTreeMap::from([(
        "9007199254740993".into(),
        json!({"first_name":"Sara","last_name":null}),
    )]);
    let value=render::json_message(&json!({"id":2,"date":1700000000,"message":"x","from_id":{"_":"peerUser","user_id":"9007199254740993"}}),&peers).unwrap();
    assert_eq!(value["from_id"], "user9007199254740993");
    assert_eq!(value["from"], "Sara");
}

#[test]
fn json_message_peer_namespaces_do_not_confuse_same_numeric_id() {
    let peers = BTreeMap::from([
        ("user:42".into(), json!({"first_name":"Person"})),
        ("channel:42".into(), json!({"title":"Channel"})),
    ]);
    let user = render::json_message(
        &json!({"id":1,"from_id":{"_":"peerUser","user_id":42}}),
        &peers,
    )
    .unwrap();
    let channel = render::json_message(
        &json!({"id":2,"from_id":{"_":"peerChannel","channel_id":42}}),
        &peers,
    )
    .unwrap();
    assert_eq!(user["from"], "Person");
    assert_eq!(channel["from"], "Channel");
}
