#[test]
fn decode_refuses_declared_pixel_bomb_before_image_data() {
    // A valid PNG header is generated by the codec, then its declared width is
    // replaced and the header CRC recomputed. The pixel limit is checked from
    // the header, before decoding the much smaller compressed pixel stream.
    let (mut data, _) = images::encode_image(&pixel_image(1, 1), "png", 64, 85, false).unwrap();
    data[16..20].copy_from_slice(&100000_u32.to_be_bytes());
    data[20..24].copy_from_slice(&100000_u32.to_be_bytes());
    let mut crc = 0xffff_ffff_u32;
    for byte in &data[12..29] {
        crc ^= u32::from(*byte);
        for _ in 0..8 {
            crc = (crc >> 1) ^ (0xedb8_8320_u32.wrapping_mul(crc & 1));
        }
    }
    data[29..33].copy_from_slice(&(!crc).to_be_bytes());
    let error = images::decode_image(&data).unwrap_err().to_string();
    assert!(error.contains("pixels"), "{error}");
}
